import { test, expect, api, aspiration, comment, reportPost, screenshot, openPostMenu } from '../support/fixtures';

test('E2E-MOD-01 laporan komentar ditindak admin, isi disamarkan dan penulis mendapat notifikasi', async ({ actors }, info) => {
  const post = await aspiration(actors.author, 'MOD E2E01 Fasilitas ruang baca');
  const text = 'Komentar MOD E2E01 yang perlu ditinjau admin.';
  const entry = await comment(actors.author, post.id, text);
  await actors.reporter.page.goto(`/aspirasi/${post.id}`);
  const item = actors.reporter.page.getByText(text, { exact: true }).locator('..');
  await item.getByRole('button', { name: 'Laporkan', exact: true }).click();
  await actors.reporter.page.getByRole('radio', { name: 'Spam', exact: true }).check();
  await actors.reporter.page.getByPlaceholder('Catatan tambahan (opsional)').fill('Konten promosi yang tidak relevan.');
  await screenshot(actors.reporter.page, info, 'MOD-01-form-laporan');
  const flagResponse = actors.reporter.page.waitForResponse(res => res.url().endsWith('/api/flags') && res.request().method() === 'POST');
  await actors.reporter.page.getByRole('button', { name: 'Kirim Laporan', exact: true }).click();
  expect((await flagResponse).status()).toBe(201);
  await actors.admin.page.goto('/admin');
  const queue = actors.admin.page.locator('#moderasi').getByRole('listitem').filter({ hasText: text });
  await expect(queue).toBeVisible();
  await screenshot(actors.admin.page, info, 'MOD-01-antrean-admin', actors.admin.page.locator('#moderasi'));
  await queue.getByRole('button', { name: 'Hapus komentar', exact: true }).click();
  const dialog = actors.admin.page.getByRole('dialog', { name: 'Hapus komentar?' });
  await expect(dialog).toBeVisible();
  const removeResponse = actors.admin.page.waitForResponse(res => res.url().endsWith(`/api/admin/comments/${entry.id}/remove`));
  await dialog.getByRole('button', { name: 'Hapus komentar', exact: true }).click();
  expect((await removeResponse).status()).toBe(200);
  await expect(queue).toHaveCount(0);
  await actors.author.page.goto(`/aspirasi/${post.id}`);
  await expect(actors.author.page.getByText('[Komentar ini telah dihapus]', { exact: true }).first()).toBeVisible();
  await expect(actors.author.page.getByText(text, { exact: true })).toHaveCount(0);
  await screenshot(actors.author.page, info, 'MOD-01-komentar-disamarkan');
  await actors.author.page.goto('/notif');
  await expect(actors.author.page.getByRole('heading', { name: 'Komentarmu dihapus oleh admin', exact: true })).toBeVisible();
  await screenshot(actors.author.page, info, 'MOD-01-notifikasi-penulis');
});

test('E2E-MOD-02 postingan ditutup menjadi read-only dan dapat dibuka kembali', async ({ actors }, info) => {
  const post = await aspiration(actors.author, 'MOD E2E02 Informasi kampus');
  await reportPost(actors.reporter, post.id);
  await actors.admin.page.goto('/admin');
  await actors.admin.page.getByRole('button', { name: 'Postingan', exact: true }).click();
  const queue = actors.admin.page.locator('#moderasi').getByRole('listitem').filter({ hasText: post.title });
  await queue.getByRole('button', { name: 'Tutup postingan', exact: true }).click();
  const dialog = actors.admin.page.getByRole('dialog', { name: 'Tutup postingan', exact: true });
  await expect(dialog.getByRole('button', { name: 'Tutup postingan', exact: true })).toBeDisabled();
  const reason = 'Informasi belum dapat diverifikasi oleh fakultas.';
  await dialog.getByLabel('Alasan penutupan').fill(reason);
  await screenshot(actors.admin.page, info, 'MOD-02-dialog-penutupan', dialog);
  const response = actors.admin.page.waitForResponse(res => res.url().endsWith(`/api/admin/posts/${post.id}/close`) && res.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Tutup postingan', exact: true }).click();
  expect((await response).status()).toBe(200);
  await actors.reporter.page.goto(`/aspirasi/${post.id}`);
  await expect(actors.reporter.page.getByText(`Alasan: ${reason}`, { exact: true })).toBeVisible();
  await expect(actors.reporter.page.getByText('Diskusi ditutup', { exact: true })).toBeVisible();
  await expect(actors.reporter.page.getByPlaceholder('Tulis balasanmu...')).toHaveCount(0);
  expect((await api(actors.reporter, 'POST', '/api/comments', { postId: post.id, content: 'Komentar harus ditolak.' })).status()).toBe(403);
  expect((await api(actors.reporter, 'POST', `/api/posts/${post.id}/upvote`)).status()).toBe(403);
  await screenshot(actors.reporter.page, info, 'MOD-02-postingan-read-only');
  await actors.author.page.goto('/notif');
  await expect(actors.author.page.getByRole('heading', { name: `Aspirasi "${post.title}" ditutup oleh admin`, exact: true })).toBeVisible();
  await actors.admin.page.goto(`/aspirasi/${post.id}`);
  await openPostMenu(actors.admin.page);
  actors.admin.page.once('dialog', event => event.accept());
  const reopen = actors.admin.page.waitForResponse(res => res.url().endsWith(`/api/admin/posts/${post.id}/close`) && res.request().method() === 'DELETE');
  await actors.admin.page.getByRole('button', { name: 'Buka Kembali', exact: true }).click();
  expect((await reopen).status()).toBe(200);
  await actors.reporter.page.reload();
  const composer = actors.reporter.page.getByPlaceholder('Tulis balasanmu...');
  await expect(composer).toBeVisible();
  await composer.fill('Diskusi dapat dilanjutkan setelah dibuka kembali.');
  const commentResponse = actors.reporter.page.waitForResponse(res => res.url().endsWith('/api/comments') && res.request().method() === 'POST');
  await composer.locator('..').getByRole('button').click();
  expect((await commentResponse).status()).toBe(201);
  await expect(actors.reporter.page.getByText('Diskusi dapat dilanjutkan setelah dibuka kembali.', { exact: true })).toBeVisible();
  await screenshot(actors.reporter.page, info, 'MOD-02-setelah-dibuka-kembali');
});

test('E2E-MOD-03 mengabaikan laporan membersihkan antrean tanpa menutup konten', async ({ actors }, info) => {
  const post = await aspiration(actors.author, 'MOD E2E03 Usulan kegiatan mahasiswa');
  await reportPost(actors.reporter, post.id);
  await actors.admin.page.goto('/admin');
  await actors.admin.page.getByRole('button', { name: 'Postingan', exact: true }).click();
  const queue = actors.admin.page.locator('#moderasi').getByRole('listitem').filter({ hasText: post.title });
  await expect(queue).toBeVisible();
  const response = actors.admin.page.waitForResponse(res => res.url().endsWith('/api/admin/flags/dismiss'));
  await queue.getByRole('button', { name: 'Abaikan laporan', exact: true }).click();
  expect((await response).status()).toBe(200);
  await expect(queue).toHaveCount(0);
  await screenshot(actors.admin.page, info, 'MOD-03-antrean-setelah-diabaikan', actors.admin.page.locator('#moderasi'));
  const detail = await api(actors.reporter, 'GET', `/api/posts/${post.id}`);
  expect((await detail.json()).data.isClosed).toBe(false);
  await actors.reporter.page.goto(`/aspirasi/${post.id}`);
  await expect(actors.reporter.page.getByText(post.content, { exact: true })).toBeVisible();
  await expect(actors.reporter.page.getByPlaceholder('Tulis balasanmu...')).toBeVisible();
  await screenshot(actors.reporter.page, info, 'MOD-03-konten-tetap-tersedia');
});

test('E2E-MOD-04 dialog hapus mobile dapat dibatalkan tanpa mengubah komentar', async ({ actors }, info) => {
  const post = await aspiration(actors.author, 'MOD E2E04 Dialog mobile');
  const entry = await comment(actors.author, post.id, 'Komentar MOD E2E04 untuk membuktikan pembatalan.');
  expect((await api(actors.reporter, 'POST', '/api/flags', { commentId: entry.id, reason: 'SPAM' })).status()).toBe(201);
  const page = actors.admin.page;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/admin');
  const queue = page.locator('#moderasi').getByRole('listitem').filter({ hasText: entry.content });
  await queue.getByRole('button', { name: 'Hapus komentar', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Hapus komentar?' });
  await expect(dialog.getByRole('button', { name: 'Batal' })).toBeFocused();
  await screenshot(page, info, 'MOD-04-dialog-mobile', dialog);
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(queue).toBeVisible();
  const comments = await api(actors.reporter, 'GET', `/api/comments?postId=${post.id}`);
  expect((await comments.json()).data.data.find((c: { id: string }) => c.id === entry.id).isDeleted).toBe(false);
  await screenshot(page, info, 'MOD-04-antrean-setelah-batal', page.locator('#moderasi'));
  await api(actors.admin, 'POST', '/api/admin/flags/dismiss', { commentId: entry.id });
});
